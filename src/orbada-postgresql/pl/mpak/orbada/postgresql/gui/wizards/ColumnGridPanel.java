package pl.mpak.orbada.postgresql.gui.wizards;

import java.awt.BorderLayout;
import java.awt.Dimension;
import java.awt.FlowLayout;
import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import javax.swing.DefaultCellEditor;
import javax.swing.JButton;
import javax.swing.JComboBox;
import javax.swing.JPanel;
import javax.swing.JScrollPane;
import javax.swing.JTable;
import javax.swing.table.DefaultTableModel;
import pl.mpak.util.StringManager;

/**
 * ORBADA 1.3.2: siatka definicji kolumn (kreator tabeli PostgreSQL i dodawania kolumn): nazwa, typ, NOT NULL, PK,
 * DEFAULT, kolumna generowana (IDENTITY, GENERATED ... STORED/VIRTUAL), komentarz.
 */
public class ColumnGridPanel extends JPanel {

  public static final int NAME = 0;
  public static final int TYPE = 1;
  public static final int NOT_NULL = 2;
  public static final int PK = 3;
  public static final int DEFAULT = 4;
  public static final int GENERATED = 5;
  public static final int COMMENT = 6;

  /** Typy podpowiadane na poczatku listy (dalej typy z bazy) */
  private static final String[] COMMON_TYPES = {
    "integer", "bigint", "smallint", "numeric(10,2)", "varchar(100)", "text", "boolean", "date", "timestamp",
    "timestamptz", "time", "interval", "uuid", "jsonb", "json", "bytea", "double precision", "real", "inet",
    "serial", "bigserial"};

  private final StringManager sm;
  private final DefaultTableModel model;
  private final JTable table;

  /**
   * @param version12 PostgreSQL 12+ (GENERATED ... STORED)
   * @param version18 PostgreSQL 18+ (GENERATED ... VIRTUAL)
   */
  public ColumnGridPanel(StringManager sm, String[] databaseTypes, boolean version10, boolean version12, boolean version18) {
    super(new BorderLayout(0, 4));
    this.sm = sm;
    model = new DefaultTableModel(new Object[] {
      sm.getString("column-name"), sm.getString("data-type"), sm.getString("not-null"), sm.getString("pk"),
      sm.getString("default-value"), sm.getString("generated-column"), sm.getString("comment")}, 0) {
      @Override
      public Class<?> getColumnClass(int column) {
        return column == NOT_NULL || column == PK ? Boolean.class : String.class;
      }
    };
    table = new JTable(model);
    table.setRowHeight(Math.max(table.getRowHeight(), new JComboBox<String>().getPreferredSize().height));
    table.setSurrendersFocusOnKeystroke(true);
    Set<String> types = new LinkedHashSet<String>();
    for (String t : COMMON_TYPES) {
      types.add(t);
    }
    if (databaseTypes != null) {
      for (String t : databaseTypes) {
        types.add(t);
      }
    }
    JComboBox<String> comboType = new JComboBox<String>(types.toArray(new String[types.size()]));
    comboType.setEditable(true);
    table.getColumnModel().getColumn(TYPE).setCellEditor(new DefaultCellEditor(comboType));
    List<String> generated = new ArrayList<String>();
    generated.add("");
    if (version10) {
      generated.add("GENERATED ALWAYS AS IDENTITY");
      generated.add("GENERATED BY DEFAULT AS IDENTITY");
      generated.add("GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1)");
    }
    if (version12) {
      generated.add("GENERATED ALWAYS AS () STORED");
    }
    if (version18) {
      generated.add("GENERATED ALWAYS AS () VIRTUAL");
    }
    JComboBox<String> comboGenerated = new JComboBox<String>(generated.toArray(new String[generated.size()]));
    comboGenerated.setEditable(true);
    table.getColumnModel().getColumn(GENERATED).setCellEditor(new DefaultCellEditor(comboGenerated));
    int[] widths = {120, 120, 50, 35, 100, 200, 150};
    for (int i = 0; i < widths.length; i++) {
      table.getColumnModel().getColumn(i).setPreferredWidth(widths[i]);
    }
    JScrollPane scroll = new JScrollPane(table);
    scroll.setPreferredSize(new Dimension(640, 180));
    add(scroll, BorderLayout.CENTER);

    JPanel buttons = new JPanel(new FlowLayout(FlowLayout.LEFT, 4, 0));
    buttons.add(button(sm.getString("column-add"), new ActionListener() {
      @Override
      public void actionPerformed(ActionEvent e) {
        stopEditing();
        model.addRow(new Object[] {"", "integer", false, false, "", "", ""});
        int row = model.getRowCount() - 1;
        table.changeSelection(row, NAME, false, false);
        table.editCellAt(row, NAME);
      }
    }));
    buttons.add(button(sm.getString("column-remove"), new ActionListener() {
      @Override
      public void actionPerformed(ActionEvent e) {
        stopEditing();
        int row = table.getSelectedRow();
        if (row >= 0) {
          model.removeRow(row);
        }
      }
    }));
    buttons.add(button(sm.getString("move-up"), new ActionListener() {
      @Override
      public void actionPerformed(ActionEvent e) {
        move(-1);
      }
    }));
    buttons.add(button(sm.getString("move-down"), new ActionListener() {
      @Override
      public void actionPerformed(ActionEvent e) {
        move(1);
      }
    }));
    add(buttons, BorderLayout.SOUTH);
  }

  private static JButton button(String text, ActionListener l) {
    JButton b = new JButton(text);
    b.addActionListener(l);
    return b;
  }

  private void move(int delta) {
    stopEditing();
    int row = table.getSelectedRow();
    if (row >= 0 && row + delta >= 0 && row + delta < model.getRowCount()) {
      model.moveRow(row, row, row + delta);
      table.changeSelection(row + delta, table.getSelectedColumn(), false, false);
    }
  }

  public void stopEditing() {
    if (table.isEditing()) {
      table.getCellEditor().stopCellEditing();
    }
  }

  public DefaultTableModel getModel() {
    return model;
  }

  public void addColumn(String name, String type, boolean notNull, boolean pk, String defaultValue, String generated, String comment) {
    model.addRow(new Object[] {name, type, notNull, pk, defaultValue, generated, comment});
  }

  private String cell(int row, int column) {
    Object o = model.getValueAt(row, column);
    return o == null ? "" : o.toString().trim();
  }

  private boolean flag(int row, int column) {
    return Boolean.TRUE.equals(model.getValueAt(row, column));
  }

  /** Definicje kolumn (bez pustych wierszy); brak typu albo wyrazenia "AS ()" - IllegalArgumentException */
  public List<String> definitions() {
    stopEditing();
    List<String> result = new ArrayList<String>();
    for (int r = 0; r < model.getRowCount(); r++) {
      if (cell(r, NAME).length() == 0) {
        continue;
      }
      String generated = cell(r, GENERATED);
      if (cell(r, TYPE).length() == 0) {
        throw new IllegalArgumentException(sm.getString("wizard-type-required") + ": " + cell(r, NAME));
      }
      if (generated.matches("(?is).*\\bAS\\s*\\(\\s*\\).*")) {
        throw new IllegalArgumentException(sm.getString("wizard-generated-expression") + ": " + cell(r, NAME));
      }
      result.add(PgWizard.ident(cell(r, NAME)) + " " + cell(r, TYPE) +
        (generated.length() > 0 ? " " + generated : "") +
        (generated.length() == 0 && cell(r, DEFAULT).length() > 0 ? " DEFAULT " + cell(r, DEFAULT) : "") +
        (flag(r, NOT_NULL) ? " NOT NULL" : ""));
    }
    return result;
  }

  /** Kolumny klucza glownego, oddzielone przecinkami, albo "" */
  public String primaryKey() {
    stopEditing();
    StringBuilder sb = new StringBuilder();
    for (int r = 0; r < model.getRowCount(); r++) {
      if (cell(r, NAME).length() > 0 && flag(r, PK)) {
        sb.append(sb.length() > 0 ? ", " : "").append(PgWizard.ident(cell(r, NAME)));
      }
    }
    return sb.toString();
  }

  /** COMMENT ON COLUMN dla kolumn z komentarzem; table - nazwa tabeli w SQL */
  public void comments(String table, List<String> sql) {
    stopEditing();
    for (int r = 0; r < model.getRowCount(); r++) {
      if (cell(r, NAME).length() > 0 && cell(r, COMMENT).length() > 0) {
        sql.add("COMMENT ON COLUMN " + table + "." + PgWizard.ident(cell(r, NAME)) + " IS " + PgWizard.literal(cell(r, COMMENT)));
      }
    }
  }

}
